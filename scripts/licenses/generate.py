#!/usr/bin/env python3
"""Writes the "Rust libraries" part of THIRD_PARTY_LICENSES.md, from what Cargo.lock says the programs are built from.

Run it after anything changes Cargo.lock's third-party packages; a test (the_licenses_list_the_libraries_of_cargo_lock)
fails until it has been. Needs cargo-about: cargo install cargo-about --locked --features cli

Everything above the marker in the file is written by hand and stays as it is. The output depends only on Cargo.lock,
so running it twice changes nothing. It stops rather than write a list it cannot stand behind: a license about.toml
does not accept, a notice it cannot find, or a library that has moved in a way the notes below no longer describe.
"""

import hashlib
import json
import re
import subprocess
import sys
import tempfile
import textwrap
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LICENSES = ROOT / "THIRD_PARTY_LICENSES.md"
LOCK = ROOT / "Cargo.lock"
MARKER = "<!-- Everything below this line is generated by scripts/licenses/generate.py"

OWN_CRATES = {"quickai", "quickai-core", "quickai-run", "quickai-runtime"}
PLACEHOLDER = re.compile(r"<year>|\[year\]|<copyright holders?>|\[fullname\]|<owner>|<organization>", re.I)

# Libraries that say MIT and whose package holds no file with their notice: the notice in their repository (or, where
# the repository's license file names nobody, the authors their Cargo.toml names), by that repository.
NOTICES_BY_REPOSITORY = {
    "AccessKit/accesskit": "Copyright (c) The AccessKit contributors",
    "SSheldon/rust-dispatch": "Copyright (c) Steven Sheldon",
    "emilk/egui": "Copyright (c) 2018-2021 Emil Ernerfeldt <emil.ernerfeldt@gmail.com>",
    "Michael-F-Bryan/include_dir": "Copyright (c) 2017 Michael Bryan",
    "aclysma/profiling": "Copyright (c) 2020 Philip Degarmo and other contributors",
    "jedisct1/rust-siphash": "Copyright 2012-2016 The Rust Project Developers.\nCopyright 2016-2026 Frank Denis.",
    "madsmtm/objc2": "Copyright 2026 Mads Marquart",
    "retep998/winapi-rs": "Copyright (c) 2015-2018 The winapi-rs Developers",
}

# Files with notices that cargo-about does not pick up: (library, file, what it is).
FURTHER_NOTICES = [
    ("epaint_default_fonts", "fonts/Hack-Regular.txt", "the Hack font, which egui embeds"),
    ("ring", "third_party/fiat/LICENSE", "the Fiat Cryptography code in ring"),
    ("ring", "src/polyfill/once_cell/LICENSE-MIT", "the once_cell code in ring"),
    ("uds_windows", "THIRDPARTYNOTICES", "the code uds_windows takes from others"),
]

INTRODUCTION = """\
QuickAI's programs are built from the open-source Rust libraries listed here, for Linux, Windows and macOS, so a
library may be in the programs for only one of those systems. Each keeps its own license. A library that offers a
choice is used under the first of these that it offers: MIT, Apache-2.0, ISC, BSD, Zlib. The list covers what goes into
the programs, not what is only used to build and test them. Each name links to the library and its source on
[crates.io](https://crates.io)."""

STANDARD_LIBRARY = """\
### The Rust standard library

Every program contains parts of Rust's standard library, © its contributors, dual-licensed under
the MIT License and the Apache License 2.0, whose texts are below. The notices of what it is made from are in
[Rust's COPYRIGHT file](https://github.com/rust-lang/rust/blob/main/COPYRIGHT) and in `COPYRIGHT-library.html` in the
documentation installed with Rust."""

WINDOWS_RUNTIME = """\
### The runtime of the Windows programs

The Windows programs are built with the mingw-w64 toolchain and contain parts of its runtime libraries: those of
mingw-w64, © the mingw-w64 project and others, and GCC's `libgcc`, under the GNU General Public License with the GCC
Runtime Library Exception. The notices of mingw-w64, as packaged in that toolchain, follow; they cover all of mingw-w64,
most of which is not in the programs."""


def fingerprint(lock_text):
    """What the list was generated from: the third-party packages of Cargo.lock, not QuickAI's own versions."""
    packages = []
    for entry in lock_text.split("[[package]]")[1:]:
        fields = dict(re.findall(r'^(name|version|source) = "([^"]*)"', entry, re.M))
        if "source" in fields:
            packages.append(f"{fields['name']} {fields['version']}")
    return hashlib.sha256("\n".join(sorted(packages)).encode()).hexdigest()


def about():
    subprocess.run(["cargo", "fetch", "--locked"], cwd=ROOT, check=True)
    with tempfile.TemporaryDirectory() as scratch:
        out = Path(scratch) / "about.json"
        subprocess.run(
            ["cargo", "about", "generate", "--frozen", "--format", "json", "-c", str(HERE / "about.toml"), "-o", str(out)],
            cwd=ROOT,
            check=True,
        )
        return json.loads(out.read_text())


def tidy(text):
    """A license text as it reads, without what editors and packaging did to its white space."""
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    return textwrap.dedent("\n".join(lines)).strip("\n")


def repository(package):
    found = re.search(r"github\.com/([^/]+/[^/]+)", package.get("repository") or "")
    return found.group(1).removesuffix(".git") if found else None


def crate_dir(package):
    return Path(package["manifest_path"]).parent


def own_notice(package, generic_mit):
    """The MIT notice of a library cargo-about could not place: the file it has that cargo-about did not recognise, or
    the one its repository has."""
    for path in sorted(crate_dir(package).iterdir()):
        if path.is_file() and re.search(r"licen[cs]e|copying|mit", path.name, re.I) and path.suffix != ".rs":
            text = path.read_text(errors="replace")
            if "Permission is hereby granted" in text and not PLACEHOLDER.search(text):
                return tidy(text)
    notice = NOTICES_BY_REPOSITORY.get(repository(package))
    if notice is None:
        sys.exit(f"{package['name']} says MIT but has no notice: add {repository(package)} to NOTICES_BY_REPOSITORY")
    return "\n".join(notice if PLACEHOLDER.search(line) else line for line in generic_mit.split("\n"))


def blocks_of(data, packages):
    """Each license text once, with the libraries that use it: (license name, text) -> {package id}."""
    blocks = defaultdict(set)
    texts = {}

    def add(name, text, package):
        key = (name, re.sub(r"\s+", " ", text))
        texts.setdefault(key, text)
        blocks[key].add(package["id"])

    for license in data["licenses"]:
        text = tidy(license["text"])
        for use in license["used_by"]:
            package = packages[use["crate"]["id"]]
            if package["name"] in OWN_CRATES:
                continue
            # ring's own files repeat, year by year, the notice its LICENSE-other-bits gives for all of them
            if package["name"] == "ring" and license["id"] == "ISC" and re.match(r"(//|/\*) *Copyright [\d-]+ Brian Smith", text):
                continue
            if license["id"] == "MIT" and PLACEHOLDER.search(text):
                text_of_crate = own_notice(package, text)
                add(license["name"], text_of_crate, package)
            else:
                add(license["name"], text, package)
    return {key: (texts[key], ids) for key, ids in blocks.items()}


def fenced(text):
    longest = max((len(run) for run in re.findall(r"`{3,}", text)), default=2)
    fence = "`" * (longest + 1)
    return f"{fence}\n{text}\n{fence}"


def named(package):
    return f"[{package['name']} {package['version']}](https://crates.io/crates/{package['name']}/{package['version']})"


def by_name(package):
    return (package["name"], [int(part) if part.isdigit() else 0 for part in re.split(r"[.+-]", package["version"])])


def winit_section(packages, by_crate_name, lock_text):
    """QuickAI's copy of winit leaves out KDE's blur protocol, so that no protocol under the LGPL reaches the programs.
    Stops if one is on its way back in: see vendor/README.md."""
    if 'name = "wayland-protocols-plasma"' in lock_text:
        sys.exit("wayland-protocols-plasma is back in Cargo.lock, and its protocols are mostly LGPL: see vendor/README.md.")
    for package in packages.values():
        if {"wayland-protocols-misc", "smithay-client-toolkit"} & {dep["name"] for dep in package["dependencies"]}:
            for path in (crate_dir(package) / "src").rglob("*.rs"):
                if "server_decoration" in path.read_text(errors="replace"):
                    sys.exit(f"{package['name']} now uses KDE's server-decoration protocol, which is under the LGPL: read {path}.")
    winit = by_crate_name["winit"]
    return (
        "### winit, changed for QuickAI\n\n"
        f"The programs use {named(winit)}, under the Apache License 2.0, with one change: the code for KDE's window blur "
        "protocol is taken out, because QuickAI never asks for a blurred window. The changed copy is in `vendor/winit` of "
        "[QuickAI's source](https://github.com/everybodyai/quickai), and `vendor/README.md` there says what was changed.\n\n"
        "Releases up to 0.2.3 use winit unchanged. Their window program for Linux contains code generated from `blur.xml`, "
        "KDE's description of that protocol, © 2015 Martin Gräßlin and 2015 Marco Martin, under the "
        "[GNU Lesser General Public License 2.1 or later](https://www.gnu.org/licenses/old-licenses/lgpl-2.1.html), which "
        "reaches winit through [wayland-protocols-plasma](https://crates.io/crates/wayland-protocols-plasma), a library "
        "under the MIT License. Later releases do not contain it."
    )


def further_notices_section(by_crate_name):
    parts = ["### Further notices\n\nNotices some libraries keep in files of their own."]
    for name, file, what in FURTHER_NOTICES:
        package = by_crate_name[name]
        path = crate_dir(package) / file
        if not path.is_file():
            sys.exit(f"{name} {package['version']} has no {file}: read what it has now and change FURTHER_NOTICES.")
        parts.append(f"From {named(package)}, {what} (`{file}`):\n\n{fenced(tidy(path.read_text(errors='replace')))}")
    return "\n\n".join(parts)


def generated(lock_text):
    data = about()
    packages = {crate["package"]["id"]: crate["package"] for crate in data["crates"]}
    by_crate_name = {}
    for package in sorted(packages.values(), key=by_name):
        by_crate_name[package["name"]] = package  # the newest of each name

    blocks = blocks_of(data, packages)
    for (license, _), (text, _) in blocks.items():
        if license != "Apache License 2.0" and PLACEHOLDER.search(text):
            sys.exit(f"a {license} text still has a blank to fill in:\n{text[:400]}")

    users = defaultdict(set)
    for (license, _), (_, ids) in blocks.items():
        users[license].update(ids)
    order = sorted(users, key=lambda license: (-len(users[license]), license))
    third_party = {package_id for ids in users.values() for package_id in ids}

    out = [
        f"{MARKER} from Cargo.lock {fingerprint(lock_text)}. Do not edit it by hand. -->",
        "## Rust libraries",
        INTRODUCTION,
        f"{len(third_party)} libraries, under these licenses (some under more than one):",
        "| License | Libraries |\n|---|---|\n" + "\n".join(f"| {license} | {len(users[license])} |" for license in order),
        STANDARD_LIBRARY,
        WINDOWS_RUNTIME,
        fenced(tidy((HERE / "mingw-w64-copyright.txt").read_text())),
        winit_section(packages, by_crate_name, lock_text),
        further_notices_section(by_crate_name),
    ]
    for license in order:
        out.append(f"### {license}")
        sections = [(sorted((packages[i] for i in ids), key=by_name), text) for (name, _), (text, ids) in blocks.items() if name == license]
        for crates, text in sorted(sections, key=lambda section: by_name(section[0][0])):
            out.append("Used by " + ", ".join(named(package) for package in crates) + ":\n\n" + fenced(text))
    return "\n\n".join(out) + "\n"


def main():
    by_hand = LICENSES.read_text().split(MARKER)[0].rstrip("\n")
    LICENSES.write_text(by_hand + "\n\n" + generated(LOCK.read_text()))
    print(f"wrote {LICENSES.relative_to(ROOT)}: {LICENSES.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
